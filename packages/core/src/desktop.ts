/**
 * The desktop layer's product brain: the `desktop` config section (tiling via
 * AeroSpace, window borders via JankyBorders, the system corner radius) and the
 * pure renderers that turn it into what the tools consume — an `aerospace.toml`,
 * `borders` CLI flags, `defaults(1)` arguments. No I/O: Rust writes the file,
 * spawns the processes, and reloads (plans/done/v0.4-desktop-aerospace-borders.md,
 * DECISIONS 2026-08-17).
 *
 * The toml template is Mitch's daily config (dotfiles/macos/desktop/aerospace)
 * minus the personal/sketchybar bits. Everything not exposed as a knob is opinion,
 * on purpose; the escape hatch is `tiling.managed = false`, after which launcharr
 * never touches the file again.
 */

export type Modifier = 'alt' | 'ctrl' | 'cmd' | 'ctrl-alt' | 'alt-shift'
export const MODIFIERS: readonly Modifier[] = [
  'alt',
  'ctrl',
  'cmd',
  'ctrl-alt',
  'alt-shift',
]

export type BorderStyle = 'round' | 'square'

export interface TilingConfig {
  /** Tiling is part of this install at all (AeroSpace expected/supervised). */
  enabled: boolean
  /** launcharr owns ~/.config/aerospace/aerospace.toml. false = hand-edited, never written. */
  managed: boolean
  /** Prefix for every main-mode binding (`alt-h`, `ctrl-alt-h`, …). */
  modifier: Modifier
  /** Inner + outer gap in px. */
  gaps: number
  /** Persistent (always shown) workspaces 1..N, N ≤ 9; keys 1–9 always bind. */
  workspaces: number
  /** Bundle ids that always float. */
  float: string[]
}

export interface BordersConfig {
  enabled: boolean
  /** Border width in px (JankyBorders `width=`). */
  width: number
  style: BorderStyle
}

export interface DesktopConfig {
  tiling: TilingConfig
  borders: BordersConfig
  /** System window corner radius (`NSConvolutionOverride1`); null = leave macOS alone. */
  cornerRadius: number | null
}

export const DEFAULT_DESKTOP: DesktopConfig = {
  tiling: {
    enabled: true,
    managed: true,
    modifier: 'alt',
    gaps: 8,
    workspaces: 6,
    float: ['com.apple.systempreferences', 'com.raycast.macos'],
  },
  borders: { enabled: false, width: 5, style: 'round' },
  cornerRadius: null,
}

/** Mirrors the shape Rust persists verbatim; anything unknown collapses to defaults. */
export function normalizeDesktop(raw: unknown): DesktopConfig {
  const r = isRecord(raw) ? raw : {}
  const t = isRecord(r.tiling) ? r.tiling : {}
  const b = isRecord(r.borders) ? r.borders : {}
  const d = DEFAULT_DESKTOP
  return {
    tiling: {
      enabled: bool(t.enabled, d.tiling.enabled),
      managed: bool(t.managed, d.tiling.managed),
      modifier: MODIFIERS.includes(t.modifier as Modifier)
        ? (t.modifier as Modifier)
        : d.tiling.modifier,
      gaps: num(t.gaps, d.tiling.gaps),
      workspaces: num(t.workspaces, d.tiling.workspaces),
      float: Array.isArray(t.float)
        ? t.float.filter((x): x is string => typeof x === 'string')
        : d.tiling.float,
    },
    borders: {
      enabled: bool(b.enabled, d.borders.enabled),
      width: num(b.width, d.borders.width),
      style: b.style === 'square' ? 'square' : 'round',
    },
    cornerRadius:
      typeof r.cornerRadius === 'number' && Number.isFinite(r.cornerRadius)
        ? r.cornerRadius
        : null,
  }
}

