// JankyBorders

export interface BorderColors {
  /** Focused-window border. */
  accent: string
  /** Unfocused-window border (drawn at half alpha). */
  dim: string
  /** Faint fill behind the border. */
  bg: string
}

const INACTIVE_ALPHA = 0.5
const BACKGROUND_ALPHA = 48 / 255
export const BORDER_WIDTH_MIN = 1
export const BORDER_WIDTH_MAX = 20

/** Arguments for `borders …` (no config file: flags are the config, rendered from the theme). */
export function bordersArgs(
  desktop: DesktopConfig,
  colors: BorderColors,
): string[] {
  const width = clamp(
    Number.isFinite(desktop.borders.width) ? desktop.borders.width : 5,
    BORDER_WIDTH_MIN,
    BORDER_WIDTH_MAX,
  )
  return [
    `active_color=${cssToBordersColor(colors.accent)}`,
    `inactive_color=${cssToBordersColor(colors.dim, INACTIVE_ALPHA)}`,
    `background_color=${cssToBordersColor(colors.bg, BACKGROUND_ALPHA)}`,
    `width=${trimNumber(width)}`,
    'hidpi=on',
    `style=${desktop.borders.style === 'square' ? 'square' : 'round'}`,
  ]
}

/** CSS colour (#rgb, #rrggbb, #rrggbbaa, rgb()/rgba()) → JankyBorders `0xAARRGGBB`. */
export function cssToBordersColor(css: string, alphaOverride?: number): string {
  const parsed = parseCss(css.trim()) ?? { r: 255, g: 255, b: 255, a: 1 }
  const a = alphaOverride ?? parsed.a
  const hex = (n: number) =>
    Math.round(clamp(n, 0, 255))
      .toString(16)
      .padStart(2, '0')
  return `0x${hex(a * 255)}${hex(parsed.r)}${hex(parsed.g)}${hex(parsed.b)}`
}

function parseCss(
  s: string,
): { r: number; g: number; b: number; a: number } | null {
  const hexMatch = /^#([0-9a-f]{3,8})$/i.exec(s)
  if (hexMatch) {
    let h = hexMatch[1] ?? ''
    if (h.length === 3 || h.length === 4)
      h = h
        .split('')
        .map((c) => c + c)
        .join('')
    if (h.length !== 6 && h.length !== 8) return null
    const n = (i: number) => parseInt(h.slice(i, i + 2), 16)
    return { r: n(0), g: n(2), b: n(4), a: h.length === 8 ? n(6) / 255 : 1 }
  }
  const fn =
    /^rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)$/i.exec(
      s,
    )
  if (fn) {
    const [, r, g, b, a] = fn
    return {
      r: Number(r),
      g: Number(g),
      b: Number(b),
      a: a === undefined ? 1 : Number(a),
    }
  }
  return null
}

