// System corner radius (hidden AppKit global; verified 2026-08-17 on macOS 27.0)

export const CORNER_RADIUS_KEY = 'NSConvolutionOverride1'
/** 0 is read as "unset" by AppKit — the smallest effective value is 1. */
export const CORNER_RADIUS_MIN = 1
/** Tahoe's default; larger only makes things rounder than stock. */
export const CORNER_RADIUS_MAX = 26

export function clampCornerRadius(n: number): number {
  if (!Number.isFinite(n)) return CORNER_RADIUS_MAX
  return clampInt(n, CORNER_RADIUS_MIN, CORNER_RADIUS_MAX)
}

/** Arguments for `defaults …` — write for a radius, delete to hand control back to macOS. */
export function cornerRadiusArgs(radius: number | null): string[] {
  if (radius === null) return ['delete', '-g', CORNER_RADIUS_KEY]
  return [
    'write',
    '-g',
    CORNER_RADIUS_KEY,
    '-float',
    String(clampCornerRadius(radius)),
  ]
}

