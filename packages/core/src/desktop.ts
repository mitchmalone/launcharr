// aerospace.toml

export const GENERATED_HEADER =
  '# generated by launcharr — edit ~/.config/launcharr/config.json (Settings → Desktop),\n' +
  '# or set desktop.tiling.managed = false to take this file over by hand.'

/** Our own file? Decides adopt-or-stop on first launch and whether a rewrite is safe. */
export function isManagedToml(text: string): boolean {
  return text.startsWith('# generated by launcharr')
}

export const MAX_WORKSPACES = 9

export interface RenderOptions {
  /** Height of launcharr's bar on external displays (0 = bar off); added to the outer top gap. */
  barHeight?: number
}

export function renderAerospaceToml(
  desktop: DesktopConfig,
  opts: RenderOptions = {},
): string {
  const t = desktop.tiling
  const mod = t.modifier
  const gaps = clampInt(t.gaps, 0, 64)
  const barHeight = clampInt(opts.barHeight ?? 32, 0, 200)
  const n = clampInt(t.workspaces, 1, MAX_WORKSPACES)
  const ws = Array.from({ length: n }, (_, i) => String(i + 1))
  // Keys 1–9 always work (AeroSpace creates a workspace on demand); N only
  // decides which ones persist in the bar when empty.
  const keys = Array.from({ length: MAX_WORKSPACES }, (_, i) => String(i + 1))
  const floats = t.float
    .map((s) => s.trim())
    .filter((s) => s.length > 0 && /^[A-Za-z0-9._-]+$/.test(s))

  const lines: string[] = [
    GENERATED_HEADER,
    '',
    'config-version = 2',
    'start-at-login = true',
    '',
    "# launcharr's bar re-snapshots when anything in its triggers/ dir changes.",
    "exec-on-workspace-change = ['/bin/bash', '-c',",
    '  \'touch "$HOME/.config/launcharr/triggers/workspace"\'',
    ']',
    '',
    'enable-normalization-flatten-containers = true',
    'enable-normalization-opposite-orientation-for-nested-containers = true',
    'accordion-padding = 28',
    "default-root-container-layout = 'tiles'",
    "default-root-container-orientation = 'auto'",
    "on-focused-monitor-changed = ['move-mouse monitor-lazy-center']",
    'automatically-unhide-macos-hidden-apps = false',
    '',
    `persistent-workspaces = [${ws.map((w) => `'${w}'`).join(', ')}]`,
    '',
    '[exec]',
    'inherit-env-vars = true',
    '',
    '[exec.env-vars]',
    "PATH = '/opt/homebrew/bin:/opt/homebrew/sbin:/usr/local/bin:${PATH}'",
    '',
    '[gaps]',
    `inner.horizontal = ${gaps}`,
    `inner.vertical = ${gaps}`,
    `outer.left = ${gaps}`,
    `outer.bottom = ${gaps}`,
    '# Built-in displays reserve notch/menu-bar space already; externals add room for the bar.',
    `outer.top = [{ monitor."built-in.*" = ${gaps} }, ${gaps + barHeight}]`,
    `outer.right = ${gaps}`,
    '',
    '[mode.main.binding]',
    `${mod}-slash = 'layout tiles horizontal vertical'`,
    `${mod}-comma = 'layout accordion horizontal vertical'`,
    `${mod}-f = 'fullscreen'`,
    `${mod}-shift-space = 'layout floating tiling'`,
    '',
    `${mod}-h = 'focus left'`,
    `${mod}-j = 'focus down'`,
    `${mod}-k = 'focus up'`,
    `${mod}-l = 'focus right'`,
    '',
    "ctrl-left = 'workspace --wrap-around prev'",
    "ctrl-right = 'workspace --wrap-around next'",
    '',
    `${mod}-shift-h = 'move left'`,
    `${mod}-shift-j = 'move down'`,
    `${mod}-shift-k = 'move up'`,
    `${mod}-shift-l = 'move right'`,
    '',
    `${mod}-minus = 'resize smart -50'`,
    `${mod}-equal = 'resize smart +50'`,
    '',
    ...keys.map((w) => `${mod}-${w} = 'workspace ${w}'`),
    '',
    ...keys.map(
      (w) =>
        `${mod}-shift-${w} = ['move-node-to-workspace ${w}', 'workspace ${w}']`,
    ),
    '',
    `${mod}-tab = 'workspace-back-and-forth'`,
    `${mod}-shift-tab = 'move-workspace-to-monitor --wrap-around next'`,
    '',
    `${mod}-r = 'mode resize'`,
    `${mod}-semicolon = 'mode service'`,
    '',
    '[mode.resize.binding]',
    "h = 'resize width -50'",
    "j = 'resize height +50'",
    "k = 'resize height -50'",
    "l = 'resize width +50'",
    "minus = 'resize smart -50'",
    "equal = 'resize smart +50'",
    "esc = 'mode main'",
    "enter = 'mode main'",
    '',
    '[mode.service.binding]',
    "r = ['reload-config', 'mode main']",
    "f = ['flatten-workspace-tree', 'mode main']",
    "backspace = ['close-all-windows-but-current', 'mode main']",
    "esc = 'mode main'",
    "enter = 'mode main'",
    '',
    '[[on-window-detected]]',
    "if.app-id = 'com.apple.finder'",
    "if.window-title-regex-substring = 'Copy|Move|Info|Preferences'",
    "run = 'layout floating'",
  ]
  for (const id of floats) {
    lines.push(
      '',
      '[[on-window-detected]]',
      `if.app-id = '${id}'`,
      "run = 'layout floating'",
    )
  }
  lines.push('')
  return lines.join('\n')
}

